#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { loadReleaseManifest, validateReleaseManifest } from "./lib/release-manifest.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "docs", "CURRENT_RELEASE.md");
const checkOnly = process.argv.includes("--check");
const manifest = await loadReleaseManifest(root);
const failures = validateReleaseManifest(manifest);

if (failures.length > 0) {
  throw new Error(`Cannot render current release documentation:\n- ${failures.join("\n- ")}`);
}

const expected = renderCurrentRelease(manifest);

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== expected) {
    console.error("docs/CURRENT_RELEASE.md is stale; run npm run sync:current-release");
    process.exit(1);
  }
  console.log("docs/CURRENT_RELEASE.md is current.");
} else {
  await writeFile(outputPath, expected, "utf8");
  console.log("Generated docs/CURRENT_RELEASE.md.");
}

function renderCurrentRelease(value) {
  const engine = value.releaseGroups.engine;
  const studio = value.releaseGroups.studio;
  const site = value.releaseGroups.site;
  const surfaces = value.surfaces;
  const studioArm64 = surfaces.studio.arm64Asset.replace("{version}", studio.version);
  const studioX64 = surfaces.studio.x64Asset.replace("{version}", studio.version);
  const studioReleaseUrl =
    `https://github.com/${surfaces.studio.repository}/releases/tag/${surfaces.studio.tagPrefix}${studio.version}`;

  return `# Current Memi release truth

> Generated from \`release-manifest.json\`. Do not edit this file manually.

Manifest updated: ${value.updatedAt}

Memi is the read-only design engineering audit and skill layer for coding agents. The CLI and focused skills are primary; Studio is a companion.

| Release group | Current version | Canonical evidence |
|---|---:|---|
| CLI, npm, MCP, and Action | \`${engine.version}\` | [GitHub release](${surfaces.githubRelease.url}) · [npm](${surfaces.npm.url}) |
| Studio | \`${studio.version}\` | [Studio release](${studioReleaseUrl}) |
| Website | \`${site.version}\` | [memoire.cv](${surfaces.website.publicUrl}) |

## Immutable engine identity

- Source commit: \`${engine.sourceCommit}\`
- GitHub tag: \`${surfaces.githubRelease.tagPrefix}${engine.version}\`
- GitHub Action major channel: \`${surfaces.githubAction.majorTag}\`
- MCP server: \`${surfaces.mcp.serverName}\`

## Studio assets

- \`${studioArm64}\`
- \`${studioX64}\`
- \`${surfaces.studio.checksumAsset}\`

## Primary activation path

\`\`\`bash
npx -y @memi-design/cli@${engine.version} diagnose . --json --no-write --fail-on none
\`\`\`

This command is read-only. A successful first audit must return file-anchored findings or an explicit evidence-backed unsupported state; an empty or unassessed result is never a whole-product pass.

## Release rules

- \`release-manifest.json\` is the only version source of truth.
- Run \`npm run sync:current-release\` and \`npm run sync:release-manifest\` after committing an intentional manifest change.
- Historical launch documents must identify themselves as historical and link back to this page.
- Do not announce parity until npm, GitHub, MCP, the Action, Studio, and the deployed website match their release groups.
`;
}
